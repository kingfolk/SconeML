#!/usr/bin/env python3
"""Generate M2 production-input fixtures with an independent wrapping oracle.

Python integer operations are masked after every instruction. This script never
imports production parsers, executes SconeML, or reads compiler/backend output.
Fixtures contain the source, host arrays, launch options and explicit assertions.
"""
import argparse
import sys
from pathlib import Path

# --check must not create bytecode caches as a side effect of importing helpers.
sys.dont_write_bytecode = True
from generate import MASK, annotation, numbers, signed

ROOT = Path(__file__).resolve().parents[1] / 'acceptance_m2'
SEED = 0x5C0E0002


def reference(arguments, instructions, result):
    lengths = {len(values) for values in arguments.values()}
    if len(lengths) != 1:
        raise ValueError('reference requires equal input lengths')
    output = []
    for index in range(next(iter(lengths))):
        env = {name: values[index] & MASK for name, values in arguments.items()}
        for name, op, *args in instructions:
            if op == 'constant':
                value = args[0]
            elif op == 'add':
                value = env[args[0]] + env[args[1]]
            elif op == 'sub':
                value = env[args[0]] - env[args[1]]
            elif op == 'mul':
                value = env[args[0]] * env[args[1]]
            else:
                raise ValueError(op)
            env[name] = value & MASK
        output.append(signed(env[result]))
    return output


def program(arity):
    # Source text is explicit; expectations use a separate instruction list.
    # The source also exercises precedence, left associativity and repeated use.
    if arity == 1:
        return ('a * a + 17 * a - 2147483647', [
            ('s', 'mul', 'a', 'a'), ('n', 'constant', 17),
            ('p', 'mul', 'n', 'a'), ('q', 'add', 's', 'p'),
            ('m', 'constant', 2147483647), ('out', 'sub', 'q', 'm')], 'out')
    if arity == 2:
        return ('b - a * b + a - b', [
            ('p', 'mul', 'a', 'b'), ('q', 'sub', 'b', 'p'),
            ('r', 'add', 'q', 'a'), ('out', 'sub', 'r', 'b')], 'out')
    return ('c - a * b + a * a - b', [
        ('p', 'mul', 'a', 'b'), ('q', 'sub', 'c', 'p'),
        ('s', 'mul', 'a', 'a'), ('r', 'add', 'q', 's'),
        ('out', 'sub', 'r', 'b')], 'out')


def check_oracle():
    anchors = [
        ({'a': [2]}, program(1)[1], 'out', [-2147483609]),
        ({'a': [2], 'b': [3]}, program(2)[1], 'out', [-4]),
        ({'a': [2147483647], 'b': [1]},
         [('y', 'add', 'a', 'b')], 'y', [-2147483648]),
        ({'a': [-2147483648], 'b': [1]},
         [('y', 'sub', 'a', 'b')], 'y', [2147483647]),
        ({'a': [65536, -1, -2147483648], 'b': [65536, -1, -1]},
         [('y', 'mul', 'a', 'b')], 'y', [0, 1, -2147483648]),
        ({'a': [2], 'b': [3], 'c': [5]}, program(3)[1], 'out', [0]),
        ({'a': [], 'b': [], 'c': []}, program(3)[1], 'out', []),
    ]
    for arrays, ops, result, expected in anchors:
        if reference(arrays, ops, result) != expected:
            raise ValueError(f'M2 oracle anchor failed: {arrays}')
    try:
        reference({'a': [], 'b': [1]}, [], 'a')
    except ValueError:
        pass
    else:
        raise ValueError('oracle accepted mismatched inputs')


def arrays(arity, length, seed):
    result = {}
    for i, name in enumerate('abc'[:arity]):
        # Independent streams and displaced anchor patterns catch buffer swaps;
        # full-width signed data is supplied by the caller, not source literals.
        values = numbers(length + i, seed + i * 0x9E3779B9)
        result[name] = values[i:]
    return result


def case(expression, instructions, result, runs):
    text = ('(* Generated by test/reference/generate_m2.py; do not edit. *)\n'
            f'(* Seed: 0x{SEED:08x}. Independent modulo-2^32 expectations. *)\n'
            '(* @test\nversion: 1\ninput: source\nruns:\n')
    for name, pipeline, arguments, width in runs:
        text += f'  - name: {name}\n    pipeline: {pipeline}\n'
        if width is not None:
            text += f'    threads-per-group: {width}\n'
        text += '    arguments:\n'
        for variable, values in arguments.items():
            text += f'      - name: "{variable}"\n        values: {values}\n'
    text += '*)\n'
    for name, pipeline, arguments, _ in runs:
        text += annotation(name, 'result', str(reference(arguments, instructions, result)), False)
        if pipeline == 'tensor-input-metal':
            text += annotation(name, 'compare', 'cpu', False)
    return text + expression + '\n'


def fixtures():
    output = {}
    for arity in (1, 2, 3):
        expression, ops, result = program(arity)
        grouped = []
        for width in (1, 4, 32, 256):
            for length in sorted({0, 1, width - 1, width, width + 1, 2 * width + 1}):
                values = arrays(arity, length, SEED + arity * 1000 + length)
                # Declaration order intentionally differs from source use order.
                values = dict(reversed(list(values.items())))
                runs = [('cpu', 'tensor-input-cpu', values, None),
                        ('metal', 'tensor-input-metal', values, width),
                        ('metal-auto', 'tensor-input-metal', values, None)]
                grouped.append(f'(* @case w{width}-n{length:03d} *)\n' + case(
                    expression, ops, result, runs))
        arity_name = {1: 'single', 2: 'two', 3: 'three'}[arity]
        output[f'matrix/{arity_name}-input-launch-boundaries.ml'] = '\n'.join(grouped)

    # Unused arguments must still determine/validate length and occupy ABI slots.
    values = arrays(3, 9, SEED)
    for name, expression, ops, result in [
        ('unused', 'b - b + a', [('z', 'sub', 'b', 'b'),
                               ('out', 'add', 'z', 'a')], 'out'),
        ('constant', '2147483647', [('out', 'constant', 2147483647)], 'out')]:
        output[f'{name}.ml'] = case(expression, ops, result, [
            ('cpu', 'tensor-input-cpu', values, None),
            ('metal', 'tensor-input-metal', values, 4)])

    expression, ops, result = program(3)
    output['lifetime.ml'] = case(expression, ops, result, [
        ('cpu', 'tensor-input-cpu', arrays(3, 11, SEED), None),
        ('changed', 'tensor-input-cpu', arrays(3, 11, SEED + 1), None),
        ('metal', 'tensor-input-metal', arrays(3, 11, SEED), 4)])
    # Direct C++ contracts additionally bind these arrays to overlapping spans.
    overlap = {'a': [10, 20, 30], 'b': [20, 30, 40], 'c': [30, 40, 50]}
    output['overlap.ml'] = case(expression, ops, result, [
        ('cpu', 'tensor-input-cpu', overlap, None),
        ('metal', 'tensor-input-metal', overlap, 4)])
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify without writing')
    args = parser.parse_args()
    check_oracle()
    expected = fixtures()
    if args.check:
        actual = {str(p.relative_to(ROOT)) for p in ROOT.rglob('*') if p.is_file()}
        if actual != set(expected):
            raise SystemExit(f'M2 fixture set differs: {actual ^ set(expected)}')
        for name, text in expected.items():
            if (ROOT / name).read_text() != text:
                raise SystemExit(f'stale M2 fixture: {name}')
        print(f'PASS M2 independent oracle anchors and {len(expected)} generated fixtures')
    else:
        for name, text in expected.items():
            path = ROOT / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        print(f'Generated {len(expected)} M2 fixtures; seed 0x{SEED:08x}')


if __name__ == '__main__':
    main()
