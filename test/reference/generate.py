#!/usr/bin/env python3
"""Generate self-contained F5 fixtures with an independent modulo-2^32 oracle.

No compiler, MLIR, production parser, or execution outputs are used. Python's
unbounded integers are reduced after every operation; signed output is a bit
interpretation, never signed machine arithmetic. --check is read-only.
"""
import argparse
from pathlib import Path

MASK = (1 << 32) - 1
SEED = 0x5C0E2026
ROOT = Path(__file__).resolve().parents[1] / 'acceptance'


def signed(bits):
    bits &= MASK
    return bits if bits < (1 << 31) else bits - (1 << 32)


def reference(values, instructions, result):
    outputs = []
    for value in values:
        env = {'x': value & MASK}
        for name, op, *args in instructions:
            if op == 'constant':
                bits = args[0]
            else:
                lhs, rhs = (env[arg] for arg in args)
                if op == 'add':
                    bits = lhs + rhs
                elif op == 'sub':
                    bits = lhs - rhs
                elif op == 'mul':
                    bits = lhs * rhs
                else:
                    raise ValueError(op)
            env[name] = bits & MASK
        outputs.append(signed(env[result]))
    return outputs


# Small hand-calculated anchors protect the oracle's wrapping and signed view.
def check_oracle():
    anchors = [
        (signed(0x80000000), -2147483648),
        (signed(0xffffffff), -1),
        (signed(0x100000000), 0),
        (reference([2147483647], [('one', 'constant', 1),
                    ('y', 'add', 'x', 'one')], 'y'), [-2147483648]),
        (reference([-2147483648], [('one', 'constant', 1),
                    ('y', 'sub', 'x', 'one')], 'y'), [2147483647]),
        (reference([65536, -1, -2147483648],
                    [('y', 'mul', 'x', 'x')], 'y'), [0, 1, 0]),
        (reference([-3], [('s', 'mul', 'x', 'x'),
                    ('y', 'add', 's', 's')], 'y'), [18]),
    ]
    for actual, expected in anchors:
        if actual != expected:
            raise ValueError(f'oracle anchor: expected {expected}, actual {actual}')



PROGRAMS = {
    'identity': ([], 'x'),
    'add': ([('one', 'constant', 1), ('y', 'add', 'x', 'one')], 'y'),
    'sub': ([('one', 'constant', 1), ('y', 'sub', 'x', 'one')], 'y'),
    'mul': ([('three', 'constant', 3), ('y', 'mul', 'x', 'three')], 'y'),
    'negate': ([('zero', 'constant', 0), ('y', 'sub', 'zero', 'x')], 'y'),
    'shared': ([('s', 'mul', 'x', 'x'), ('y', 'add', 's', 's')], 'y'),
    'bits': ([('max', 'constant', 2147483647),
              ('min', 'constant', -2147483648), ('neg', 'constant', -1),
              ('zero', 'constant', 0), ('sum', 'add', 'x', 'max'),
              ('prod', 'mul', 'sum', 'min'), ('diff', 'sub', 'prod', 'neg'),
              ('y', 'add', 'diff', 'zero')], 'y'),
    'mixed': ([('a', 'constant', -2147483647), ('b', 'constant', 65537),
               ('s', 'mul', 'x', 'x'), ('p', 'mul', 's', 'b'),
               ('d', 'sub', 'p', 'a'), ('y', 'add', 'd', 'x')], 'y'),
}


def numbers(length, state):
    anchors = [-2147483648, 2147483647, -1, 0, 1, 46340, 46341,
               65536, 1073741824, -1073741824]
    values = anchors[:length]
    while len(values) < length:
        # Explicit xorshift32 makes the stream independent of Python RNG versions.
        state ^= (state << 13) & MASK
        state ^= state >> 17
        state ^= (state << 5) & MASK
        state &= MASK
        values.append(signed(state))
    return values


def annotation(name, kind, text, ir):
    if ir:
        return '\n'.join('// ' + line for line in
                         [f'@assert:{name}:{kind}', *text.splitlines(), '@end']) + '\n'
    return f'(* @assert:{name}:{kind}\n{text}\n*)\n'


def ir_case(length, width, program, index):
    values = numbers(length, SEED + index)
    if length == 1:
        values = [2147483647]
    ops, result = PROGRAMS[program]
    expected = reference(values, ops, result)
    lines = ['// Generated by test/reference/generate.py; do not edit.',
             f'// Seed: 0x{SEED:08x}; case {index}; program {program}.',
             '// @test', '// version: 1', '// input: mlir',
             f'// tensor-input: {values}', '// runs:',
             '//   - name: cpu', '//     pipeline: tensor-cpu-ir',
             '//   - name: metal', '//     pipeline: tensor-metal-ir',
             f'//     threads-per-group: {width}',
             '//   - name: metal-auto', '//     pipeline: tensor-metal-ir',
             '// @end']
    text = '\n'.join(lines) + '\n'
    for name in ['cpu', 'metal', 'metal-auto']:
        text += annotation(name, 'result', str(expected), True)
        if name != 'cpu':
            text += annotation(name, 'compare', 'cpu', True)
            text += annotation(name, 'source-unchanged', 'true', True)
            text += annotation(name, 'entrypoint', 'tensor_map', True)
    if program == 'shared':
        text += annotation('metal', 'ir-check',
            'CHECK: %[[X:.*]] = memref.load\n'
            'CHECK-NEXT: %[[S:.*]] = arith.muli %[[X]], %[[X]] : i32\n'
            'CHECK-NEXT: %[[Y:.*]] = arith.addi %[[S]], %[[S]]', True)
    buffer = f'memref<{length}xi32>'
    text += f'''module {{
  func.func @map_source(%input: {buffer}, %output: {buffer}) {{
    "letalg.tensor_map"(%input, %output) ({{
    ^bb0(%x: i32):
'''
    for name, op, *args in ops:
        if op == 'constant':
            text += f'      %{name} = arith.constant {args[0]} : i32\n'
        else:
            text += f'      %{name} = arith.{op}i %{args[0]}, %{args[1]} : i32\n'
    text += f'''      letalg.yield %{result} : i32
    }}) : ({buffer}, {buffer}) -> ()
    func.return
  }}
}}
'''
    return text


def source_case(name, values, expression, instructions, result, width):
    expected = reference(values, instructions, result)
    text = f'''(* Generated by test/reference/generate.py; do not edit. *)
(* @test
version: 1
input: source
runs:
  - name: cpu
    pipeline: tensor-cpu
  - name: metal
    pipeline: tensor-metal
    threads-per-group: {width}
*)
'''
    text += annotation('cpu', 'result', str(expected), False)
    text += annotation('metal', 'result', str(expected), False)
    text += annotation('metal', 'compare', 'cpu', False)
    return text + f'let xs = {values} in {expression}\n'


def fixtures():
    matrix = [(0, 4, 'identity'), (1, 1, 'add'), (3, 4, 'sub'),
              (4, 4, 'mul'), (5, 4, 'negate'), (31, 32, 'shared'),
              (32, 32, 'bits'), (33, 32, 'mixed'), (255, 256, 'add'),
              (256, 256, 'sub'), (257, 256, 'mul'), (513, 32, 'mixed')]
    result = {f'ir/{n:03d}-{program}.mlir': ir_case(n, w, program, i)
              for i, (n, w, program) in enumerate(matrix)}
    source_programs = [
        ('add', 'xs + 1', *PROGRAMS['add']),
        ('sub', '0 - xs - 1', [('zero', 'constant', 0),
         ('one', 'constant', 1), ('neg', 'sub', 'zero', 'x'),
         ('y', 'sub', 'neg', 'one')], 'y'),
        ('square', 'xs * xs', [('y', 'mul', 'x', 'x')], 'y'),
        ('polynomial', 'xs * xs + 17 * xs - 2147483647',
         [('a', 'constant', 17), ('b', 'constant', 2147483647),
          ('s', 'mul', 'x', 'x'), ('p', 'mul', 'a', 'x'),
          ('sum', 'add', 's', 'p'), ('y', 'sub', 'sum', 'b')], 'y'),
    ]
    for name, expression, instructions, target in source_programs:
        # Source syntax only supports nonnegative i32 literals. Signed and
        # extreme host inputs are tested explicitly at the raw IR boundary.
        values = [0, 1, 46341, 65536, 1073741824, 2147483647]
        result[f'source/{name}.ml'] = source_case(
            name, values, expression, instructions, target, 4)
    result['source/empty-rejected.ml'] = """(* Generated by test/reference/generate.py; do not edit. *)
(* @test
version: 1
input: source
runs:
  - name: cpu
    pipeline: tensor-cpu
  - name: metal
    pipeline: tensor-metal
*)
(* @assert:cpu:error
stage: frontend
message: tensor literal cannot be empty
*)
(* @assert:metal:error
stage: frontend
message: tensor literal cannot be empty
*)
let xs = [] in xs
"""
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify without writing')
    args = parser.parse_args()
    check_oracle()
    expected = fixtures()
    if args.check:
        actual = {str(p.relative_to(ROOT)) for p in ROOT.rglob('*') if p.is_file()}
        if actual != set(expected):
            raise SystemExit(f'fixture set differs: {actual ^ set(expected)}')
        for name, text in expected.items():
            if (ROOT / name).read_text() != text:
                raise SystemExit(f'stale fixture: {name}')
        print(f'PASS independent oracle anchors and {len(expected)} generated fixtures')
    else:
        for name, text in expected.items():
            path = ROOT / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        print(f'Generated {len(expected)} fixtures; seed 0x{SEED:08x}')


if __name__ == '__main__':
    main()
